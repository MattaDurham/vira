"""The module tree - modules/<module>/<submodule>/, the density ladder for code.

AGENTS.md is a 46-line router that sends an agent to one longer file. This
tree is the same shape, one level deeper, for the code itself:

    AGENTS.md                      "you are changing code: start here"
      modules/README.md            every module, one line each
        modules/work/README.md     one module: its submodules, one line each
          modules/work/automations/README.md
                                   one submodule: every file it owns, what
                                   each is, what it reads and feeds, its
                                   routes, stores and tests

An agent reads down the ladder until it has what it needs and stops. Each
README carries a breadcrumb back up and links sideways to the submodules it
reads from and feeds, so "I am here, I need to go there" is always one
click, and the leaf holds all the detail.

Two kinds of file sit in the tree:

  - module.json     the manifest: the files the submodule owns (globs over
                    the tracked tree), its route prefixes, stores, the
                    submodules it reads and feeds, and the system-map
                    records that describe it. Hand-edited.
  - README.md       prose above, a generated block below. The prose is the
                    author's; the block between the `moduletree:begin` and
                    `moduletree:end` markers is rendered from the manifest
                    and the tree by `index --write`, so the file tables can
                    never drift from the code. `check` fails when they have.

The tree describes where things belong; it does not (yet) move them. A
submodule's files still live in server/, static/, tests/ and scripts/;
`plan <id>` prints the `git mv` list that would gather them, one submodule
at a time, when that migration is wanted.

CLI (from a checkout, `python -m server.moduletree ...`):

  tree                print the tree with file counts
  check               every tracked file in scope is owned by exactly one
                      submodule, every link resolves, every generated block
                      is current. Exit 1 on any problem. tests/test_moduletree
                      runs this on every PR.
  index [--write]     render the generated blocks; --write updates the READMEs
  brief <id>          the agent brief for a submodule (work/automations) or a
                      module (work): the README plus the full module docstring
                      of every server file it owns
  plan <id>           the git mv list that would gather a submodule's files
  where <path>        which submodule owns a file
"""
import fnmatch
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TREE = ROOT / "modules"

# Directories every tracked file of which must be claimed by a submodule.
# Root-level files (AGENTS*.md, README.md, LICENSE, .gitignore) sit above the
# tree and are not claimed; a manifest may still claim one explicitly.
SCOPE = ("server", "static", "tests", "scripts", "android", "bridge",
         "fixtures", "walkthroughs", "walkthrough_anon")

GROUPS = {
    "communicate": "Communicate",
    "know": "Know",
    "operate": "Operate",
    "rhythm": "Rhythm",
    "money": "Money",
}
GROUP_ORDER = ("communicate", "know", "operate", "rhythm", "money")

BEGIN = "<!-- moduletree:begin"
END = "<!-- moduletree:end -->"
BEGIN_LINE = ("<!-- moduletree:begin - generated by "
              "`python -m server.moduletree index --write` from module.json; "
              "edit the manifest, not this block -->")

KINDS = (
    ("Server", lambda p: p.startswith("server/")),
    ("Frontend", lambda p: p.startswith("static/")),
    ("Tests", lambda p: p.startswith("tests/")),
    ("Scripts", lambda p: p.startswith("scripts/")),
    ("Other", lambda p: True),
)


# ---------------------------------------------------------------- loading

class TreeError(Exception):
    pass


def _read_json(path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        raise TreeError(f"{path.relative_to(ROOT)}: {e}")


def load():
    """The whole tree: {"modules": [module, ...]} in README order.

    A module is its module.json plus "submodules": [submodule, ...], each
    submodule its module.json plus "module": the parent id and "dir": its
    folder. Order comes from the module manifest's "submodules" list; a
    folder that list omits is appended (and reported by check).
    """
    modules = []
    if not TREE.is_dir():
        raise TreeError("modules/ is missing")
    for mdir in sorted(p for p in TREE.iterdir() if p.is_dir()):
        mj = mdir / "module.json"
        if not mj.exists():
            continue
        mod = _read_json(mj)
        mod["dir"] = mdir
        mod.setdefault("id", mdir.name)
        listed = list(mod.get("submodules") or [])
        present = sorted(p.name for p in mdir.iterdir()
                         if p.is_dir() and (p / "module.json").exists())
        order = [s for s in listed if s in present] + \
                [s for s in present if s not in listed]
        subs = []
        for sname in order:
            sub = _read_json(mdir / sname / "module.json")
            sub["dir"] = mdir / sname
            sub["module"] = mod["id"]
            sub.setdefault("id", f"{mod['id']}/{sname}")
            subs.append(sub)
        mod["submodules"] = subs
        mod["_listed"] = listed
        mod["_present"] = present
        modules.append(mod)
    order = {g: i for i, g in enumerate(GROUP_ORDER)}
    modules.sort(key=lambda m: (order.get(m.get("group"), 99),
                                m.get("rank", 50), m["id"]))
    return {"modules": modules}


def submodules(tree):
    for mod in tree["modules"]:
        for sub in mod["submodules"]:
            yield sub


def find(tree, ident):
    """A module or submodule by id ("work" or "work/automations")."""
    for mod in tree["modules"]:
        if mod["id"] == ident:
            return mod
        for sub in mod["submodules"]:
            if sub["id"] == ident:
                return sub
    return None


# ----------------------------------------------------------- the tracked tree

def tracked_files():
    """Every tracked path under ROOT, posix-relative, plus any new file git
    does not ignore: a file just written shows up as unplaced before it is
    added, not after CI runs. git first; a walk when git is unavailable (an
    exported tree), skipping what .gitignore would."""
    try:
        out = subprocess.run(["git", "ls-files", "-z", "--cached", "--others",
                              "--exclude-standard"], cwd=str(ROOT),
                             capture_output=True, timeout=30, check=True)
        files = [f for f in out.stdout.decode("utf-8", "replace").split("\0")
                 if f]
        if files:
            return sorted(files)
    except (OSError, subprocess.SubprocessError, UnicodeDecodeError):
        pass
    skip = {".git", ".venv", ".worktrees", ".claude", "__pycache__",
            "node_modules", "data", "docs", "retros", ".playwright-mcp",
            ".aquarium-build"}
    files = []
    for base, dirs, names in os.walk(ROOT):
        dirs[:] = [d for d in dirs if d not in skip]
        for n in names:
            if n.endswith((".pyc", ".log")) or n == ".DS_Store":
                continue
            files.append(Path(base, n).relative_to(ROOT).as_posix())
    return sorted(files)


def in_scope(path):
    return path.split("/", 1)[0] in SCOPE and "/" in path


def matches(pattern, path):
    """A manifest glob against a posix path. `dir/**` is everything under
    dir; otherwise fnmatch, where `*` does not cross a slash."""
    if pattern.endswith("/**"):
        return path.startswith(pattern[:-2])
    if pattern == path:
        return True
    if "*" not in pattern and "?" not in pattern and "[" not in pattern:
        return False
    # fnmatch's * crosses slashes; keep each * inside one path segment.
    rx = "".join("[^/]*" if ch == "*" else re.escape(ch) if ch not in "?["
                 else ("[^/]" if ch == "?" else "[")
                 for ch in pattern)
    return re.fullmatch(rx, path) is not None


def owned(sub, files):
    """The tracked files a submodule's manifest claims, in tree order."""
    pats = list(sub.get("owns") or [])
    return [f for f in files if any(matches(p, f) for p in pats)]


def ownership(tree, files=None):
    """{path: [submodule ids claiming it]} for every tracked file."""
    files = files if files is not None else tracked_files()
    claims = {}
    for sub in submodules(tree):
        for f in owned(sub, files):
            claims.setdefault(f, []).append(sub["id"])
    return claims


# ------------------------------------------------------------- descriptions

_PY_DOC = re.compile(r'^\s*(?:#![^\n]*\n)?(?:#[^\n]*\n|\s)*[rRuU]{0,2}("""|\'\'\')(.*?)\1',
                     re.S)
_BLOCK = re.compile(r"^\s*/\*+\s*(.*?)\*/", re.S)
_LINE = re.compile(r"^(?:\s*(?://|#)[^\n]*\n?)+")


def describe(path):
    """One line saying what a file is: the first sentence of its module
    docstring or leading comment, or an empty string."""
    full = ROOT / path
    if not full.is_file() or full.suffix in (".json", ".png", ".jpg", ".webp",
                                             ".glb", ".ico", ".svg", ".gif",
                                             ".txt", ".webmanifest", ".kt",
                                             ".jar", ".bat", ".lock", ".kts"):
        return ""
    try:
        text = full.read_text(encoding="utf-8", errors="replace")[:4000]
    except OSError:
        return ""
    body = ""
    if full.suffix == ".py":
        m = _PY_DOC.match(text)
        body = m.group(2) if m else ""
    elif full.suffix in (".js", ".mjs", ".css"):
        m = _BLOCK.match(text)
        if m:
            body = m.group(1)
        else:
            m = _LINE.match(text)
            body = re.sub(r"^\s*//", "", m.group(0), flags=re.M) if m else ""
    elif full.suffix in (".sh", ".ps1", ".zsh") or full.name == "run.sh":
        lines = []
        for ln in text.splitlines()[1:] if text.startswith("#!") \
                else text.splitlines():
            if ln.startswith("#"):
                lines.append(ln.lstrip("# ").rstrip())
            elif lines:
                break
        body = " ".join(lines)
    elif full.suffix in (".html",):
        m = re.search(r"<title>([^<]*)</title>", text)
        body = m.group(1) if m else ""
        m2 = _BLOCK.match(text.split("<!--", 1)[1].rsplit("-->", 1)[0]
                          if "<!--" in text and "-->" in text else "")
        if "<!--" in text:
            cm = re.search(r"<!--\s*(.*?)-->", text, re.S)
            if cm:
                body = cm.group(1)
    elif full.suffix == ".md":
        for ln in text.splitlines():
            if ln.strip() and not ln.startswith("#"):
                body = ln
                break
    body = re.sub(r"\s+", " ", body).strip(" -*")
    body = body.replace("|", "\\|")
    # The first sentence, within reason.
    m = re.match(r"(.{20,160}?[.!?])(\s|$)", body)
    if m:
        body = m.group(1)
    if len(body) > 160:
        body = body[:157].rstrip() + "..."
    return body


# ------------------------------------------------------------------- routes

_APP_ROUTE = re.compile(r'^@(app|router|\w+)\.(get|post|put|delete|patch)\(\s*"([^"]*)"',
                        re.M)
_PREFIX = re.compile(r'(\w+)\s*=\s*APIRouter\(\s*prefix\s*=\s*"([^"]*)"')


def routes():
    """Every HTTP route the server declares: [(method, path, server file)].
    main.py's @app routes plus every APIRouter in server/ with its prefix."""
    found = []
    for py in sorted((ROOT / "server").glob("*.py")):
        try:
            text = py.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        prefixes = {name: pre for name, pre in _PREFIX.findall(text)}
        for var, method, path in _APP_ROUTE.findall(text):
            pre = "" if var == "app" else prefixes.get(var, "")
            if var != "app" and var not in prefixes and "APIRouter(" not in text:
                continue
            found.append((method.upper(), pre + path, f"server/{py.name}"))
    return found


def route_matches(prefix, path):
    """A manifest route prefix against a declared path. `/api/x` covers
    `/api/x` and everything under it; `/api/x$` covers `/api/x` only. The
    literal `{uid}` in a declared path matches the same text in a prefix."""
    if prefix.endswith("$"):
        return path == prefix[:-1]
    return path == prefix or path.startswith(prefix.rstrip("/") + "/")


def routes_for(sub, all_routes=None):
    all_routes = all_routes if all_routes is not None else routes()
    pres = list(sub.get("routes") or [])
    return [(method, path, src) for method, path, src in all_routes
            if any(route_matches(p, path) for p in pres)]


# ---------------------------------------------------------------- rendering

def rel(frm, to):
    return Path(os.path.relpath(to, frm)).as_posix()


def _link(frm_dir, node):
    return f"[{node['name']}]({rel(frm_dir, node['dir'] / 'README.md')})"


def _sublink(tree, frm_dir, ident):
    node = find(tree, ident)
    if node is None:
        return f"`{ident}` (missing)"
    if "/" in ident:
        mod = find(tree, node["module"])
        return f"[{mod['name']} / {node['name']}]({rel(frm_dir, node['dir'] / 'README.md')})"
    return _link(frm_dir, node)


def crumb(tree, node):
    """`Vira > Modules > Work > Automations`, each step a link."""
    d = node["dir"]
    parts = [f"[Modules]({rel(d, TREE / 'README.md')})"]
    if "module" in node:
        mod = find(tree, node["module"])
        parts.append(_link(d, mod))
        parts.append(node["name"])
    else:
        parts.append(node["name"])
    return "Vira > " + " > ".join(parts)


def render_sub(tree, sub, files=None, all_routes=None):
    files = files if files is not None else tracked_files()
    all_routes = all_routes if all_routes is not None else routes()
    d = sub["dir"]
    out = [BEGIN_LINE, ""]
    reads = sub.get("reads") or []
    feeds = sub.get("feeds") or []
    out.append("**Reads from:** " + (", ".join(_sublink(tree, d, r) for r in reads)
                                      if reads else "nothing outside itself"))
    out.append("")
    out.append("**Feeds:** " + (", ".join(_sublink(tree, d, f) for f in feeds)
                                 if feeds else "no other module directly"))
    out.append("")
    mine = owned(sub, files)
    out.append(f"### Files ({len(mine)})")
    out.append("")
    if not mine:
        out.append("No tracked files yet.")
        out.append("")
    for kind, pred in KINDS:
        rows = [f for f in mine if pred(f)]
        mine = [f for f in mine if f not in rows]
        if not rows:
            continue
        out.append(f"**{kind}**")
        out.append("")
        out.append("| File | What it is |")
        out.append("|---|---|")
        for f in rows:
            out.append(f"| `{f}` | {describe(f)} |")
        out.append("")
    rts = routes_for(sub, all_routes)
    out.append(f"### Routes ({len(rts)})")
    out.append("")
    if sub.get("routes"):
        out.append("Prefixes: " + ", ".join(f"`{p}`" for p in sub["routes"]))
        out.append("")
    if rts:
        for method, path, src in rts:
            # main.py is the default home of a route; name only the routers.
            where = "" if src == "server/main.py" else f" ({src})"
            out.append(f"- `{method} {path}`{where}")
    else:
        out.append("None: this submodule has no HTTP surface of its own.")
    out.append("")
    stores = sub.get("stores") or []
    out.append(f"### Stores ({len(stores)})")
    out.append("")
    if stores:
        out.append("Instance state under git-ignored `data/`; never hand-edit "
                   "(see `AGENTS.local.md`, section 5).")
        out.append("")
        for s in stores:
            out.append(f"- `{s}`")
    else:
        out.append("None: nothing of its own under `data/`.")
    out.append("")
    reg = sub.get("registry") or []
    out.append("### System map")
    out.append("")
    if reg:
        out.append("Registry records in `server/modulemap.py` (the System Map "
                   "window renders them): " + ", ".join(f"`{r}`" for r in reg))
    else:
        out.append("No registry record of its own yet; it is described by its "
                   "module's records.")
    out.append("")
    out.append("### Agent brief")
    out.append("")
    out.append(f"`python -m server.moduletree brief {sub['id']}` prints this "
               "page and the full module docstring of every server file above.")
    out.append("")
    out.append(END)
    return "\n".join(out)


def render_module(tree, mod, files=None):
    files = files if files is not None else tracked_files()
    d = mod["dir"]
    out = [BEGIN_LINE, ""]
    out.append("### Submodules")
    out.append("")
    for sub in mod["submodules"]:
        n = len(owned(sub, files))
        out.append(f"- {_link(d, sub)} - {sub.get('summary', '')} "
                   f"({n} file{'s' if n != 1 else ''})")
    out.append("")
    reads, feeds = [], []
    for sub in mod["submodules"]:
        for r in sub.get("reads") or []:
            m = r.split("/")[0]
            if m != mod["id"] and m not in reads:
                reads.append(m)
        for f in sub.get("feeds") or []:
            m = f.split("/")[0]
            if m != mod["id"] and m not in feeds:
                feeds.append(m)
    out.append("### Neighbours")
    out.append("")
    out.append("**Reads from:** " + (", ".join(_sublink(tree, d, r) for r in reads)
                                      if reads else "no other module"))
    out.append("")
    out.append("**Feeds:** " + (", ".join(_sublink(tree, d, f) for f in feeds)
                                 if feeds else "no other module directly"))
    out.append("")
    wins = mod.get("windows") or []
    out.append("### In the app")
    out.append("")
    if wins:
        out.append("Window" + ("s" if len(wins) > 1 else "") + ": " +
                   ", ".join(f"`{w}`" for w in wins) +
                   " (ids from `WINDOWS` in `static/app.js`).")
    else:
        out.append("No window of its own: it runs underneath every window.")
    out.append("")
    total = sum(len(owned(s, files)) for s in mod["submodules"])
    out.append(f"{total} tracked files across {len(mod['submodules'])} "
               f"submodules. `python -m server.moduletree brief {mod['id']}` "
               "prints every submodule's page in one go.")
    out.append("")
    out.append(END)
    return "\n".join(out)


def render_root(tree, files=None):
    files = files if files is not None else tracked_files()
    out = [BEGIN_LINE, ""]
    for g in GROUP_ORDER:
        mods = [m for m in tree["modules"] if m.get("group") == g]
        if not mods:
            continue
        out.append(f"### {GROUPS[g]}")
        out.append("")
        for mod in mods:
            n = sum(len(owned(s, files)) for s in mod["submodules"])
            subs = ", ".join(s["name"] for s in mod["submodules"])
            out.append(f"- {_link(TREE, mod)} - {mod.get('summary', '')}  ")
            out.append(f"  {subs} ({n} files)")
        out.append("")
    claims = ownership(tree, files)
    scoped = [f for f in files if in_scope(f)]
    unclaimed = [f for f in scoped if f not in claims]
    out.append(f"{len(scoped) - len(unclaimed)} of {len(scoped)} tracked files "
               f"in scope are placed; {len(unclaimed)} unplaced. "
               "`python -m server.moduletree check` lists any that are.")
    out.append("")
    out.append(END)
    return "\n".join(out)


def _splice(text, block):
    """README text with its generated block replaced (or appended)."""
    i = text.find(BEGIN)
    j = text.find(END)
    if i < 0 or j < 0 or j < i:
        return text.rstrip("\n") + "\n\n" + block + "\n"
    return text[:i] + block + text[j + len(END):]


def _current_block(text):
    i = text.find(BEGIN)
    j = text.find(END)
    if i < 0 or j < 0 or j < i:
        return None
    return text[i:j + len(END)]


def _norm(s):
    return s.replace("\r\n", "\n") if s is not None else None


def index(tree=None, write=False, files=None):
    """Render every generated block. Returns the READMEs that are stale
    (relative paths); with write=True they are rewritten first."""
    tree = tree or load()
    files = files if files is not None else tracked_files()
    all_routes = routes()
    jobs = [(TREE / "README.md", render_root(tree, files))]
    for mod in tree["modules"]:
        jobs.append((mod["dir"] / "README.md", render_module(tree, mod, files)))
        for sub in mod["submodules"]:
            jobs.append((sub["dir"] / "README.md",
                         render_sub(tree, sub, files, all_routes)))
    stale = []
    for path, block in jobs:
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            text = ""
        if _norm(_current_block(text)) == _norm(block) and text:
            continue
        stale.append(path.relative_to(ROOT).as_posix())
        if write:
            if not text:
                node = None
                for cand in [tree] + tree["modules"] + list(submodules(tree)):
                    if cand is not tree and cand["dir"] / "README.md" == path:
                        node = cand
                text = (f"# {node['name'] if node else 'Vira modules'}\n\n"
                        + (crumb(tree, node) + "\n\n" if node else "")
                        + (node.get("summary", "") + "\n\n" if node else ""))
            path.write_text(_splice(text, block), encoding="utf-8", newline="\n")
    return stale


# -------------------------------------------------------------------- check

def check(tree=None, files=None):
    """Every problem with the tree, as (severity, message). Severity is
    "error" (check fails) or "warn"."""
    problems = []
    try:
        tree = tree or load()
    except TreeError as e:
        return [("error", str(e))]
    files = files if files is not None else tracked_files()
    if not (TREE / "README.md").exists():
        problems.append(("error", "modules/README.md is missing"))
    ids = set()
    for mod in tree["modules"]:
        if not (mod["dir"] / "README.md").exists():
            problems.append(("error", f"{mod['id']}: README.md is missing"))
        if mod.get("group") not in GROUPS:
            problems.append(("error", f"{mod['id']}: group must be one of "
                             f"{', '.join(GROUPS)}"))
        for s in mod["_present"]:
            if s not in mod["_listed"]:
                problems.append(("error", f"{mod['id']}: submodule folder "
                                 f"'{s}' is not listed in module.json"))
        for s in mod["_listed"]:
            if s not in mod["_present"]:
                problems.append(("error", f"{mod['id']}: module.json lists "
                                 f"submodule '{s}' but there is no folder"))
        if not mod["submodules"]:
            problems.append(("error", f"{mod['id']}: no submodules"))
        ids.add(mod["id"])
        for sub in mod["submodules"]:
            ids.add(sub["id"])
            if not (sub["dir"] / "README.md").exists():
                problems.append(("error", f"{sub['id']}: README.md is missing"))
            if not sub.get("summary"):
                problems.append(("error", f"{sub['id']}: summary is empty"))
            for pat in sub.get("owns") or []:
                if not any(matches(pat, f) for f in files):
                    problems.append(("warn", f"{sub['id']}: owns pattern "
                                     f"'{pat}' matches no tracked file"))
    for sub in submodules(tree):
        for key in ("reads", "feeds"):
            for target in sub.get(key) or []:
                if target not in ids:
                    problems.append(("error", f"{sub['id']}: {key} unknown "
                                     f"id '{target}'"))
                if target == sub["id"]:
                    problems.append(("warn", f"{sub['id']}: {key} itself"))
    claims = ownership(tree, files)
    for f in files:
        if not in_scope(f):
            continue
        who = claims.get(f)
        if not who:
            problems.append(("error", f"unplaced: {f} (add it to a "
                             "module.json 'owns' list)"))
    for f, who in claims.items():
        if len(who) > 1:
            problems.append(("error",
                             f"{f}: claimed by {', '.join(sorted(who))}"))
    all_routes = routes()
    known = {r[1] for r in all_routes}
    for sub in submodules(tree):
        for p in sub.get("routes") or []:
            if not any(route_matches(p, path) for path in known):
                problems.append(("warn", f"{sub['id']}: route prefix '{p}' "
                                 "matches no declared route"))
    try:
        from . import modulemap
        reg = {m["id"] for m in modulemap.DEFAULT_MODULES}
        for sub in submodules(tree):
            for r in sub.get("registry") or []:
                if r not in reg:
                    problems.append(("warn", f"{sub['id']}: registry id "
                                     f"'{r}' is not in modulemap.DEFAULT_MODULES"))
    except Exception:  # the registry is a convenience here, never a gate
        pass
    for path in index(tree, write=False, files=files):
        problems.append(("error", f"{path}: generated block is stale; run "
                         "`python -m server.moduletree index --write`"))
    return problems


# -------------------------------------------------------------------- brief

def _full_doc(path):
    full = ROOT / path
    try:
        text = full.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""
    m = _PY_DOC.match(text)
    return m.group(2).strip() if m else ""


def brief(tree, node, files=None):
    files = files if files is not None else tracked_files()
    subs = [node] if "module" in node else node["submodules"]
    out = []
    for sub in subs:
        out.append((sub["dir"] / "README.md").read_text(encoding="utf-8").rstrip())
        docs = [(f, _full_doc(f)) for f in owned(sub, files)
                if f.startswith("server/") and f.endswith(".py")]
        docs = [(f, d) for f, d in docs if d]
        if docs:
            out.append("")
            out.append(f"## Module docstrings ({sub['id']})")
            for f, d in docs:
                out.append("")
                out.append(f"### {f}")
                out.append("")
                out.append(d)
        out.append("")
        out.append("-" * 72)
    return "\n".join(out)


def plan(sub, files=None):
    """`git mv` lines gathering a submodule's files under its folder. The
    target keeps each file's original top-level folder as a subfolder
    (server/, static/, tests/, scripts/), so imports and static paths are
    the only thing a real move has to rewrite."""
    files = files if files is not None else tracked_files()
    out = [f"# {sub['id']}: files that would move under "
           f"modules/{sub['id']}/. Nothing here runs by itself.",
           "# A real move also rewrites `from . import x` in server/ and the",
           "# static paths in index.html; see modules/README.md, 'Moving code'."]
    for f in owned(sub, files):
        top, _, rest = f.partition("/")
        if not rest:
            continue
        out.append(f"git mv {f} modules/{sub['id']}/{top}/{rest}")
    return "\n".join(out)


def tree_text(tree, files=None):
    files = files if files is not None else tracked_files()
    out = ["modules/"]
    for g in GROUP_ORDER:
        mods = [m for m in tree["modules"] if m.get("group") == g]
        if not mods:
            continue
        out.append(f"  [{GROUPS[g]}]")
        for mod in mods:
            total = sum(len(owned(s, files)) for s in mod["submodules"])
            out.append(f"  {mod['id']}/  {mod['name']}  ({total})")
            for sub in mod["submodules"]:
                out.append(f"    {sub['dir'].name}/  {sub['name']}  "
                           f"({len(owned(sub, files))})")
    return "\n".join(out)


# ---------------------------------------------------------------------- CLI

def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    cmd = argv[0] if argv else "tree"
    args = argv[1:]
    try:
        tree = load()
    except TreeError as e:
        print(f"error: {e}")
        return 1
    files = tracked_files()
    if cmd == "tree":
        print(tree_text(tree, files))
        return 0
    if cmd == "check":
        problems = check(tree, files)
        for sev, msg in problems:
            print(f"{sev}: {msg}")
        errors = sum(1 for s, _ in problems if s == "error")
        warns = len(problems) - errors
        print(f"{errors} error{'s' if errors != 1 else ''}, {warns} warning"
              f"{'s' if warns != 1 else ''}")
        return 1 if errors else 0
    if cmd == "index":
        write = "--write" in args
        stale = index(tree, write=write, files=files)
        for p in stale:
            print(("updated " if write else "stale ") + p)
        if not stale:
            print("every generated block is current")
        return 0 if (write or not stale) else 1
    if cmd in ("brief", "plan", "where"):
        if not args:
            print(f"usage: moduletree {cmd} <id>")
            return 2
        if cmd == "where":
            claims = ownership(tree, files)
            who = claims.get(args[0].replace(os.sep, "/"))
            print(", ".join(who) if who else "unplaced")
            return 0 if who else 1
        node = find(tree, args[0])
        if node is None:
            print(f"no module or submodule '{args[0]}'; see modules/README.md")
            return 1
        if cmd == "brief":
            print(brief(tree, node, files))
        else:
            subs = [node] if "module" in node else node["submodules"]
            print("\n\n".join(plan(s, files) for s in subs))
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
